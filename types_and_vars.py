# Store personal information using different Python data types.
name = "Franky Ndalle"
age = 33
height = 1.75

# Print an introduction using the variables above.
print(f"Hello, my name is {name}. I am {age} years old and {height} meters tall.")

# Use addition to calculate my age five years from now.
future_age = age + 5
print(f"In 5 years, I will be {future_age} years old.")

# Use subtraction to calculate how many years remain until age 40.
years_until_40 = 40 - age
print(f"I will turn 40 in {years_until_40} years.")

# Use multiplication to calculate the area of a rectangle.
rectangle_width = 5.5
rectangle_height = 2
rectangle_area = rectangle_width * rectangle_height
print(
    f"The area of a {rectangle_width} x {rectangle_height} "
    f"rectangle is {rectangle_area}."
)

